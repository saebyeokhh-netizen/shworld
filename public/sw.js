/**
 * 스스로를 지우는 서비스 워커.
 *
 * ── 왜 이런 것이 필요한가 ─────────────────────────────────────────────────
 *  2026-09-05 이전에는 이 도메인 맨 위에 게임(메두사 미용실)이 있었고, 게임의 서비스 워커가
 *  `/sw.js` 에 등록돼 있었다. 서비스 워커는 **자기 파일이 놓인 폴더 아래를 전부 맡는다.**
 *  그러니 그 워커가 맡은 범위는 `/` — 이 사이트 전체다.
 *
 *  게임이 `/m-hairsalon` 아래로 내려간 뒤에도 **이미 방문했던 기기에는 그 워커가 그대로
 *  남아 있다.** 그리고 그 워커는 이렇게 동작한다.
 *
 *   - 화면 이동 요청을 가로채 먼저 네트워크에 묻고, 실패하면 **캐시에 넣어둔 옛 게임 화면**을
 *     내준다. 그 화면이 부르는 `/assets/index-....js` 는 이제 없다(404) → 흰 화면
 *   - 옛 주소(`/home`)는 이제 새 자리로 넘어가는데(301), 워커가 그 **넘어간 응답**을 화면
 *     이동 요청에 그대로 돌려주면 브라우저가 거부한다 → 아무것도 안 뜬다
 *
 *  홈 화면에 앱을 설치해 둔 사람은 앱을 눌러도 안 들어가진다. 실제로 그런 제보를 받았다.
 *
 * ── 왜 파일을 지우는 것으로는 안 되나 ────────────────────────────────────
 *  브라우저는 이 주소를 다시 받아 보고 **내용이 바뀌었을 때만** 워커를 갈아끼운다. 파일이
 *  없어서 404 가 나면 갈아끼우기가 실패하고 **옛 워커가 그대로 남는다.** 없애려면 오히려
 *  새 워커를 하나 내줘야 하고, 그 새 워커가 하는 일이 **자기 자신을 지우는 것**이다.
 *
 * ── 게임의 워커는 건드리지 않는다 ────────────────────────────────────────
 *  지금 게임의 워커는 `/m-hairsalon/sw.js` 다. 주소가 다르므로 이 파일과 아무 상관이 없고,
 *  그쪽은 자기 폴더 아래만 맡는다.
 *
 *  ⚠️ `fetch` 를 듣지 않는다. 아무것도 가로채지 않아야 페이지가 곧바로 네트워크에서 온다.
 */

self.addEventListener('install', () => {
  // 기다리지 않고 곧바로 이 워커로 갈아탄다 — 옛 워커를 한 번이라도 더 쓰게 두지 않는다
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      // 옛 워커가 넣어둔 캐시를 전부 비운다. 남겨두면 이미 없는 파일을 계속 내준다
      const names = await caches.keys();
      await Promise.all(names.map((name) => caches.delete(name)));

      await self.registration.unregister();

      /*
       * 지금 열려 있는 화면을 다시 부른다.
       *
       * 등록만 지우면 **이미 열려 있는 화면은 여전히 옛 워커가 붙잡고 있다.** 사람 눈에는
       * 앱이 여전히 안 열리는 상태 그대로다. 다시 부르면 그때부터 네트워크에서 온다.
       */
      const windows = await self.clients.matchAll({ type: 'window' });
      for (const client of windows) {
        client.navigate(client.url).catch(() => {});
      }
    })(),
  );
});
